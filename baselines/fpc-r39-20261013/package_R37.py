"""Atomic audited packaging; never self-include active logs, ZIP or manifest."""
import hashlib,json,os,tempfile,zipfile
from pathlib import Path
from r37_freeze import EXPECTED_SHA,SOURCE,hash_file
ROOT=Path(__file__).resolve().parent
DEST=ROOT.parent/'RAZR_SLIDE_R37_verified_engineering_package_20261011.zip'
SHA_FILE=ROOT.parent/(DEST.name+'.sha256')
MANIFEST=ROOT/'audit/R37_package_member_manifest.json'

def run():
    assert hash_file(SOURCE)==EXPECTED_SHA
    frozen=json.loads((ROOT/'audit/R37_R36_immutable.json').read_text())
    assert len(frozen['entries'])==977
    originals={r['path']:r for r in frozen['entries']}
    for key,r in originals.items():
        p=ROOT/key
        assert p.is_file() and p.stat().st_size==r['size'] and hash_file(p)==r['sha256'],key
    results=json.loads((ROOT/'verification/R37_results.json').read_text())
    assert results['total_fresh_test_count']==661 and results['manufacturing_go'] is False
    assert (ROOT/'verification/R37_inherited_exit.code').read_text().strip()=='0'
    assert (ROOT/'verification/R37_new_exit.code').read_text().strip()=='0'
    included=[]
    for f in sorted(ROOT.rglob('*')):
        if not f.is_file() or f==MANIFEST:continue
        name=f.relative_to(ROOT).as_posix()
        # Non-inherited generated bytecode is unreviewed runtime cache.
        if ('__pycache__' in f.parts and name not in originals) or name.endswith('.tmp'):continue
        included.append(dict(path=name,size_bytes=f.stat().st_size,sha256=hash_file(f)))
    assert len(set(z['path'] for z in included))==len(included)
    manifest=dict(revision='R37 audited research archive; manufacturing NO-GO',
        source_R36_SHA256=EXPECTED_SHA,ancestor_count=len(originals),
        members_excluding_manifest=len(included),members=included)
    MANIFEST.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    members=included+[dict(path=MANIFEST.relative_to(ROOT).as_posix(),size_bytes=MANIFEST.stat().st_size,
        sha256=hash_file(MANIFEST))]
    fd,tmp=tempfile.mkstemp(dir=DEST.parent,prefix='.R37_atomic_build_',suffix='.zip')
    os.close(fd)
    try:
        with zipfile.ZipFile(tmp,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=5,allowZip64=True) as z:
            for m in members:
                z.write(ROOT/m['path'],m['path'])
        def check(path):
            with zipfile.ZipFile(path) as z:
                assert z.testzip() is None
                assert len(z.infolist())==len(members) and len(set(z.namelist()))==len(members)
                for m in members:
                    h=hashlib.sha256();length=0
                    with z.open(m['path']) as f:
                        for block in iter(lambda:f.read(2<<20),b''):
                            h.update(block);length+=len(block)
                    assert length==m['size_bytes'] and h.hexdigest()==m['sha256'],m['path']
        check(tmp)
        with open(tmp,'rb') as f:os.fsync(f.fileno())
        os.replace(tmp,DEST)
    finally:
        if os.path.exists(tmp):os.unlink(tmp)
    check(DEST)
    dig=hash_file(DEST)
    SHA_FILE.write_text(f'{dig}  {DEST.name}\n')
    assert hash_file(DEST)==dig
    output=dict(revision='R37',file=str(DEST),member_count=len(members),size_bytes=DEST.stat().st_size,
        sha256=dig,zip_crc='OK',member_sha256='OK',ancestor_members_unchanged=977,
        research_tests=661,manufacturing_go=False)
    print(json.dumps(output,ensure_ascii=False,indent=2),flush=True)
    return output
if __name__=='__main__':run()
