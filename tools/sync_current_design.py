#!/usr/bin/env python3
"""Synchronize the research overview, design and status from one current-state file.

Use --check to detect stale generated text. Historical experiments and their
pass/fail evidence are never rewritten. Unit counts come from the manifest;
the last completed run retains its own source version and scope.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OVERVIEW = Path('docs/RESEARCH_OVERVIEW.md')
START = '<!-- current-product:start -->'
END = '<!-- current-product:end -->'


def load_inputs(root: Path):
    current = json.loads((root / 'design/current_product.json').read_text())
    manifest = json.loads((root / 'tools/test_suites.json').read_text())
    suites = manifest['suites']
    if manifest['minimum_total_tests'] != sum(s['minimum_tests'] for s in suites):
        raise ValueError('test manifest total does not match its suites')
    if len({s['id'] for s in suites}) != len(suites):
        raise ValueError('duplicate test suite identity')
    if current['product_constraints']['independent_rear_display']:
        raise ValueError('current product uses only one main display')
    if current['product_constraints']['storage_mode'] != 'flat_in_B':
        raise ValueError('current product stores the screen flat in B')
    if any(p['in_main'] for p in current['open_research_prs']):
        raise ValueError('an open research PR cannot be represented as accepted main')
    return current, manifest


def short_index(current: dict, manifest: dict) -> str:
    count = manifest['minimum_total_tests']
    groups = len(manifest['suites'])
    return '\n'.join([
        START,
        '## Current product integration — ' + current.get('last_update_date', '2026-10-18'),
        '',
        '[Current design](../CURRENT_DESIGN.md) · '
        '[Machine-readable product state](../design/current_product.json) · '
        '[Implementation and evidence](../engineering/product-integration-20261018/README.md)',
        '',
        current['stage_summary'],
        '',
        'The active milestone is a common assembly with flat OLED storage, complete '
        'terminations, A/B cell reservations and an operable manual cycle. '
        'Measured parts, source specifications and project assumptions retain separate identities.',
        '',
        f'Configured unit validation: **{count} tests / {groups} suites** '
        'in `tools/test_suites.json`. Completed execution reports retain their exact '
        'commit and scope in `design/current_product.json`; a configured count is not an execution result.',
        '',
        current['verification_summary'],
        '',
        'Accepted numerical evidence: [PR34 installation/service]('
        '../engineering/installation-control-20261018/DELIVERY_VERIFICATION.json). '
        'Bearing research and the older spring experiment retain their own versioned '
        'results in the current product state; historical failures remain preserved.',
        'That FE evidence belongs to the original installation geometry. The newly '
        'modified product shells have not been structurally requalified.',
        END,
    ])


def current_design(current: dict, manifest: dict) -> str:
    parts = [
        '# Current design and product integration', '',
        '<!-- Generated by tools/sync_current_design.py from design/current_product.json. -->', '',
        current['stage_summary'], '',
        '## Product and platform', '',
        'Equal finished A/B envelopes; one approximately 7-inch flexible main OLED; '
        'flat storage in B; B moves upward 79.75 mm and seats normally by 8.20 mm; '
        'A has larger-cell priority. The 4700 mAh target uses cell-label sum at a common '
        'reference voltage; it is not verified terminal Ah for an unknown pack topology '
        'and is not a selected cell pair.', '',
        'The implementation baseline is `' + current['implementation_baseline']['commit'] + '`. '
        'The donor reuse design decision and unknown physical identities are in '
        '[product interfaces](design/product_interfaces.json); '
        'project geometry and reservation assumptions are in '
        '[product geometry](design/product_geometry.json).', '',
        '## Current work packages', '',
        '| Package | Current result | Evidence / implementation | Remaining condition |',
        '|---|---|---|---|',
    ]
    for item in current['work_packages']:
        parts.append('| ' + ' | '.join([
            item['id'], item['result'],
            f"[{item['path']}]({item['path']})", item['remaining'],
        ]) + ' |')
    parts.extend(['', '## Validation and research boundaries', '',
        f"Configured unit manifest: **{manifest['minimum_total_tests']} tests / "
        f"{len(manifest['suites'])} suites**. Run `uv run --locked python -B tools/verify.py`. "
        'Run `python3 tools/sync_current_design.py --check` to check these entry points.', '',
        current['verification_summary'], '',
    ])
    for run in current['completed_unit_runs']:
        parts.append(f"- {run['label']}: **{run['tests']} tests / {run['suites']} suites**, "
                     f"functional commit `{run['functional_commit']}`, "
                     f"scope `{run['scope']}`; [report]({run['report']}).")
    parts.extend(['',
        'Accepted PR34 evidence closes the retained normalized installation and '
        'fixed-adjustment service model. It does not determine real preload, '
        'torque, material strength or phone capacity. The original eight cases '
        'and later L1/L2 cases remain versioned results, not fresh reruns. '
        'The product candidate cuts A_FRAME, A_BACK_PANEL and B_SHELL and adds '
        'supports; the original FE closure does not structurally qualify those new solids.', '',
        '### Open research', '',
    ])
    for pr in current['open_research_prs']:
        parts.append(f"- [PR #{pr['number']}]({pr['url']}) at `{pr['head']}`: {pr['result']} "
                     f"Next: {pr['action']}")
    if current.get('closed_research_prs'):
        parts.extend(['', '### Archived research decisions', ''])
        for pr in current['closed_research_prs']:
            parts.append(f"- [PR #{pr['number']}]({pr['url']}) at `{pr['head']}`: "
                         f"{pr['result']} Resolution: {pr['resolution']}")
    parts.extend(['',
        '## Actual build and measurements', '',
        current['hardware_summary'], '',
        'Study CAD can be generated and unpowered research coupons can be prepared '
        'while physical inputs remain incomplete. A study export does not assert '
        'whole-phone fit, electrical operation or a completed physical test.', '',
        'Full implementation commands, generated outputs and measured/rejected '
        'results are in [the integration delivery](engineering/product-integration-20261018/README.md). '
        'Historical entry points remain available at the recorded baseline commit and in the original experiments.', '',
    ])
    return '\n'.join(parts)


def render_status(status: dict, current: dict, manifest: dict) -> dict:
    result = copy.deepcopy(status)
    result['current_product_state'] = 'design/current_product.json'
    result['current_production_review'] = 'CURRENT_DESIGN.md'
    result['current_execution_summary'] = current.get('current_execution_summary', 'engineering/product-integration-20261018/DELIVERY_VERIFICATION.json')
    result['current_product_stage'] = current['stage_summary']
    result['current_unit_tests'] = {
        'manifest': 'tools/test_suites.json',
        'configured_minimum': manifest['minimum_total_tests'],
        'groups': len(manifest['suites']),
        'completed_runs': current['completed_unit_runs'],
        'configured_count_is_not_a_pass': True,
    }
    result['current_fresh_verification'] = current['verification_summary']
    result['current_open_research_prs'] = current['open_research_prs']
    result['current_closed_research_prs'] = current.get('closed_research_prs', [])
    result['current_work_packages'] = current['work_packages']
    result['latest_engineering_evidence']['complete_endpoint_repair'] = 'engineering/fpc-route-endpoint-repair-20261013-r7'
    result['latest_engineering_evidence']['common_product_integration'] = 'engineering/product-integration-20261018'
    spatial = result['current_spatial_contact']
    spatial.update({
        'original_cases_passed': list(range(8)), 'original_case_rejected': None,
        'remaining_not_run': [], 'all_eight_cases_closed': True,
        'evidence': 'engineering/preload-closure-20261017/DELIVERY_VERIFICATION.json',
        'scope': 'original frozen surface and volume grid; later models are separate',
    })
    result['current_volume_refinement'].update({
        'level2_contact_completed': True,
        'completed_level2_cases': [4, 5, 6, 7],
        'completion_evidence': 'engineering/nested-contact-20261017/DELIVERY_VERIFICATION.json',
        'scope': 'L1/L2 case4-7 on unchanged original surface trace; not all-interface convergence',
    })
    # Preserve older study values, including real failed models, with their scope.
    historical_scopes = {
        'current_mechanical_mount_study': 'mounted-mechanism stage; subsequent B-to-KEY transmission is in current_transmission_study',
        'current_cover_backing_study': 'cover-backing stage; subsequent shear keys are in current_panel_shear_key_study',
        'current_contact_field_audit': 'rejected pre-contact-solve diagnostic; superseded for original cases by current_contact_closure',
        'finished_phone_space': 'historical thick-mechanism space diagnostic; current registered candidate is in design/product_geometry.json',
    }
    for key, scope in historical_scopes.items():
        if key in result:
            result[key]['historical_stage_scope'] = scope
    return result


def expected_files(root: Path) -> dict[Path, str]:
    current, manifest = load_inputs(root)
    state = render_status(json.loads((root / 'status.json').read_text()), current, manifest)
    return {
        root / OVERVIEW: '# RAZR SLIDE research overview\n\n' + short_index(current, manifest) + '\n',
        root / 'CURRENT_DESIGN.md': current_design(current, manifest),
        root / 'status.json': json.dumps(state, indent=2, ensure_ascii=False) + '\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    changed = []
    for path, content in expected_files(args.root).items():
        if not path.exists() or path.read_text() != content:
            changed.append(path.relative_to(args.root).as_posix())
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    print(json.dumps({'mode': 'check' if args.check else 'write', 'changed': changed}))
    raise SystemExit(1 if args.check and changed else 0)


if __name__ == '__main__':
    main()
